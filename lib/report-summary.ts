import {
  VERDICT_META,
  type DiagnosisInputs,
  type DiagnosisResults,
} from '@/lib/engine';

const STATUS_LABEL: Record<string, string> = {
  good: 'GOOD',
  warn: 'WATCH',
  bad: 'BAD',
  na: 'N/A',
};

/**
 * Plain-text diagnosis summary — buyers copy this into Slack, docs, or
 * client reports. No markdown, no fluff, all the numbers that matter.
 */
export function buildSummaryText(
  inputs: DiagnosisInputs,
  results: DiagnosisResults,
): string {
  const lines: string[] = [];
  const meta = VERDICT_META[results.verdict];

  lines.push(`CAMPAIGN DIAGNOSIS — ${inputs.campaignName}`);
  lines.push(`Generated by Meta Ads Signal Assistance (rule-based, D2C)`);
  lines.push('');
  lines.push(`VERDICT: ${meta.title}`);
  lines.push(results.verdictReason);
  lines.push('');

  const section = (title: string, signals: DiagnosisResults['adSignals']) => {
    if (!signals.length) return;
    lines.push(title.toUpperCase());
    for (const s of signals) {
      lines.push(`- ${s.label}: ${s.display} [${STATUS_LABEL[s.status] ?? s.status}]`);
    }
    lines.push('');
  };

  section('Ad signals', results.adSignals);
  section('Business metrics', results.businessMetrics);

  const c = results.creative;
  lines.push('CREATIVE');
  lines.push(
    `- Hook rate: ${c.hookRate !== null ? `${(c.hookRate * 100).toFixed(1)}%` : 'n/a'} [${STATUS_LABEL[c.hookStatus] ?? c.hookStatus}]`,
  );
  lines.push(
    `- Hold rate: ${c.holdRate !== null ? `${(c.holdRate * 100).toFixed(1)}%` : 'n/a'} [${STATUS_LABEL[c.holdStatus] ?? c.holdStatus}]`,
  );
  lines.push(`- ${c.fatigueNote}`);
  lines.push('');

  if (results.actionItems.length) {
    lines.push('ACTION ITEMS — DO THIS, IN ORDER');
    for (const a of results.actionItems) {
      lines.push(`${a.priority}. ${a.title}`);
      lines.push(`   ${a.detail}`);
      lines.push(`   In Ads Manager: ${a.adsManagerStep}`);
    }
    lines.push('');
  }

  lines.push('RULES THAT FIRED (with math)');
  for (const r of results.rulesFired) {
    lines.push(`- ${r.rule}: ${r.math}`);
  }
  lines.push('');
  lines.push(
    'Benchmarks are adjustable starting points, not verified platform data. ' +
      'Tune them to your account history.',
  );

  return lines.join('\n');
}
